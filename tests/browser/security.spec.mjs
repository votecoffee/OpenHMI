import { test, expect } from '@playwright/test';

test.use({ baseURL: 'http://127.0.0.1:8766' });
test('HMI groups administer and enforce button and numeric input access', async ({ page }) => {
  test.setTimeout(90000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  async function login(name) {
    await page.getByLabel('HMI user', { exact: true }).fill(name);
    await page.getByLabel('HMI password', { exact: true }).fill('SecurityTestOnly-2026!');
    await page.getByRole('button', { name: 'Sign in to HMI', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Sign out of HMI', exact: true })).toBeVisible();
  }
  await page.goto('/runtime');
  await expect(page.getByRole('button', { name: 'Toggle simulated motor', exact: true })).toBeDisabled();
  await login('admin');
  await page.getByRole('link', { name: 'Security', exact: true }).click();
  await page.getByLabel('HMI group name', { exact: true }).fill('Maintenance');
  const permissions = page.getByRole('group', { name: 'Group permissions', exact: true });
  await permissions.getByLabel('runtime.operate', { exact: true }).check();
  await permissions.getByLabel('runtime.write', { exact: true }).check();
  await page.getByLabel('Security change reason', { exact: true }).fill('Create maintenance operations group');
  await page.getByRole('button', { name: 'Save HMI group', exact: true }).click();
  await expect(page.getByRole('status', { name: 'Security operation' })).toContainText('recorded');
  await page.getByLabel('Local user name', { exact: true }).fill('maint');
  await page.getByLabel('New password (leave blank to retain existing)', { exact: true }).fill('SecurityTestOnly-2026!');
  await page.getByRole('group', { name: 'User HMI groups', exact: true }).getByLabel('Maintenance', { exact: true }).check();
  await page.getByLabel('Security change reason', { exact: true }).fill('Assign local technician to Maintenance');
  await page.getByRole('button', { name: 'Save local user', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Edit local user', exact: true })).toHaveValue('maint');
  if (process.env.OPENHMI_SECURITY_ADMIN) await page.screenshot({ path: process.env.OPENHMI_SECURITY_ADMIN, fullPage: true });
  await page.goto('/');
  await page.locator('[data-control="button"]').click();
  await page.getByRole('group', { name: 'Allowed HMI groups (any selected)', exact: true }).getByLabel('Maintenance', { exact: true }).check();
  await expect(page.getByRole('status', { name: 'Draft status' })).toContainText('saved');
  const source = await page.getByRole('button', { name: 'Numeric input', exact: true }).boundingBox();
  const target = await page.locator('.hmi-grid').boundingBox();
  await page.mouse.move(source.x + source.width / 2, source.y + source.height / 2);
  await page.mouse.down();
  await page.mouse.move(target.x + 100, target.y + 90, { steps: 10 });
  await page.mouse.move(target.x + 110, target.y + 100, { steps: 2 });
  await page.mouse.up();
  await expect(page.locator('[data-control="input"]')).toHaveCount(1);
  await page.locator('[data-control="input"]').click();
  await page.getByRole('group', { name: 'Allowed HMI groups (any selected)', exact: true }).getByLabel('Maintenance', { exact: true }).check();
  await page.getByRole('button', { name: 'Apply live', exact: true }).click();
  await expect(page.getByRole('status', { name: 'Draft status' })).toContainText('Applied live');
  await page.goto('/runtime');
  await page.getByRole('button', { name: 'Sign out of HMI', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Toggle simulated motor', exact: true })).toBeDisabled();
  await expect(page.getByLabel('Tank setpoint new value', { exact: true })).toBeDisabled();
  expect((await page.request.put('/api/controls/bogus/value', { data: { value: 25 } })).status()).toBe(404);
  await login('maint');
  await expect(page.getByRole('button', { name: 'Toggle simulated motor', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Toggle simulated motor', exact: true }).click();
  await expect(page.locator('[data-control="indicator"]')).toContainText('OFF');
  await page.getByLabel('Tank setpoint new value', { exact: true }).fill('23.5');
  await page.getByRole('button', { name: 'Write value', exact: true }).click();
  await expect(page.locator('[data-control="input"]')).toContainText('23.5');
  if (process.env.OPENHMI_SECURITY_RUNTIME) await page.screenshot({ path: process.env.OPENHMI_SECURITY_RUNTIME, fullPage: true });
  await page.goto('/');
  await expect(page.getByText('Sign in with a group that has project.edit permission to edit this HMI.')).toBeVisible();
  expect(errors).toEqual([]);
});
