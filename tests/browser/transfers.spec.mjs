import { test, expect } from '@playwright/test';
import { fileURLToPath } from 'node:url';
import { readFile } from 'node:fs/promises';

test.use({ actionTimeout: 15000 });
test('recipe transfer designer mapping, approved/test PLC copies, image and history', async ({ page }) => {
  test.setTimeout(120000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const original = (await (await page.request.get('/api/project')).json()).draft;
  async function apply(project) {
    const state = await (await page.request.get('/api/project')).json();
    const saved = await page.request.put('/api/project/draft', { data: { expected_revision: state.draft_revision, project } });
    expect(saved.ok(), await saved.text()).toBe(true);
    const applied = await page.request.post('/api/project/apply', { data: { expected_revision: (await saved.json()).draft_revision } });
    expect(applied.ok(), await applied.text()).toBe(true);
  }
  const initial = { RequestSequence: 0, AcceptedSequence: 0, CompletedSequence: 0, ResultCode: 0, Permit: true };
  const members = { RequestSequence: 'integer', AcceptedSequence: 'integer', CompletedSequence: 'integer', ResultCode: 'integer', Permit: 'boolean' };
  const fields = { RecipeCode: 'string', RevisionId: 'integer', RevisionNumber: 'integer', ContentHash: 'string', TransferHash: 'string', RecipeProductionApproved: 'boolean', Speed: 'number' };
  for (const prefix of ['Staging', 'Running']) {
    initial[prefix] = {};
    for (const [member, type] of Object.entries(fields)) { members[`${prefix}.${member}`] = type; initial[prefix][member] = type === 'string' ? '' : type === 'boolean' ? false : 0; }
  }
  const project = structuredClone(original);
  project.tags.push({ name: 'CycleCommand', type: 'struct', writable: true, members, initial });
  project.commands.push({ id: 'recipe_cycle', name: 'Recipe commit', root_tag: 'CycleCommand', permit_member: 'Permit', timeout_seconds: 30 });
  project.controls.push({ id: 'recipe_feedback', kind: 'button', label: 'Simulate recipe PLC', action: 'command_complete' });
  await apply(project);
  await page.goto('/');
  await page.getByRole('button', { name: 'PLC recipes', exact: true }).click();
  await page.getByLabel('Transfer profile ID', { exact: true }).fill('product');
  await page.getByLabel('Transfer profile name', { exact: true }).fill('Product transfer');
  await page.getByLabel('Commit command', { exact: true }).selectOption('recipe_cycle');
  await page.getByRole('button', { name: 'Add transfer profile', exact: true }).click();
  await page.getByLabel('product parameter name', { exact: true }).fill('speed');
  await page.getByLabel('product parameter member', { exact: true }).selectOption('Speed');
  await page.getByRole('button', { name: 'Add parameter mapping', exact: true }).click();
  await page.getByRole('button', { name: 'Apply live', exact: true }).click();
  await expect(page.getByRole('status', { name: 'Draft status' })).toContainText('Applied live');
  await page.goto('/recipe-editor');
  await page.getByLabel('Recipe user', { exact: true }).fill('engineer');
  await page.getByLabel('Password', { exact: true }).fill('RecipeTestOnly-2026!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByRole('button', { name: 'New recipe', exact: true }).click();
  await page.getByLabel('Recipe code', { exact: true }).fill('TRANSFER-DEMO');
  await page.getByLabel('Recipe title', { exact: true }).fill('Transfer fixture');
  await page.getByLabel('Change / approval / load reason', { exact: true }).fill('Initial PLC transfer trial');
  await page.getByLabel('Recipe image (PNG/JPEG)', { exact: true }).setInputFiles(fileURLToPath(new URL('../fixtures/recipe-part.png', import.meta.url)));
  await expect(page.getByRole('status', { name: 'Recipe operation' })).toContainText('Image uploaded');
  await page.getByRole('button', { name: 'Add parameter', exact: true }).click();
  await page.getByLabel('Parameter 1 name', { exact: true }).fill('speed');
  await page.getByLabel('Parameter 1 value', { exact: true }).fill('45.5');
  await page.getByRole('button', { name: 'Create recipe', exact: true }).click();
  await expect(page.locator('.recipe-review-state')).toContainText('draft');
  await page.getByLabel('Change / approval / load reason', { exact: true }).fill('Approve trial by its author');
  await page.getByRole('button', { name: 'Submit for approval', exact: true }).click();
  await page.getByLabel('Change / approval / load reason', { exact: true }).fill('Approve trial by its author');
  await page.getByRole('button', { name: 'Approve for production', exact: true }).click();
  await expect(page.locator('.recipe-review-state')).toContainText('approved');
  await page.getByLabel('Change / approval / load reason', { exact: true }).fill('Transfer production snapshot');
  const dispatch = page.getByRole('button', { name: 'Transfer revision to PLC', exact: true });
  await expect(dispatch).toBeEnabled();
  const displayed = await (await page.request.get('/api/recipe-transfers')).json();
  const profilesEndpoint = '**/api/recipe-transfers?*';
  await page.route(profilesEndpoint, route => route.fulfill({ json: displayed }));
  const changed = (await (await page.request.get('/api/project')).json()).active;
  changed.recipe_transfers[0].name = 'Updated product transfer';
  await apply(changed);
  await dispatch.click();
  await expect(page.getByRole('status', { name: 'Recipe operation' })).toContainText('Review and reselect the PLC transfer target');
  expect((await (await page.request.get('/api/tags')).json()).values['CycleCommand.RequestSequence']).toBe(0);
  await page.unroute(profilesEndpoint);
  const target = page.getByLabel('PLC transfer target', { exact: true });
  await expect(target.getByRole('option', { name: 'Updated product transfer' })).toHaveCount(1);
  await expect(target).toHaveValue('');
  await expect(dispatch).toBeDisabled();
  await target.selectOption('product');
  const dispatchEndpoint = '**/api/recipe-transfers/product/dispatch';
  let failStatus = false;
  await page.route(profilesEndpoint, route => failStatus
    ? route.fulfill({ status: 503, json: { detail: 'Synthetic status outage' } })
    : route.continue());
  await page.route(dispatchEndpoint, async route => {
    const response = await route.fetch();
    failStatus = response.ok();
    await route.fulfill({ response });
  });
  await dispatch.click();
  const panel = page.getByRole('region', { name: 'PLC recipe transfers', exact: true });
  await expect(panel.getByRole('alert')).toContainText('Synthetic status outage');
  await expect(page.getByRole('status', { name: 'Recipe operation' })).toContainText(/PLC transfer requested\. Transaction \d+/);
  await expect(dispatch).toBeDisabled();
  const receipts = (await (await page.request.get('/api/recipe-transfers')).json()).items;
  expect(receipts).toHaveLength(1);
  const transaction = receipts[0].transaction;
  const link = panel.getByRole('link', { name: `View command transaction #${transaction.id}`, exact: true });
  await expect(link).toHaveAttribute('href', `/commands?transaction=${transaction.id}`);
  const commandView = await page.context().newPage();
  await commandView.goto(await link.getAttribute('href'));
  const commandRow = commandView.locator('.activity-table tbody tr');
  await expect(commandRow).toHaveCount(1);
  await expect(commandRow).toContainText('requested');
  await expect(commandRow.getByText(`Operation ${transaction.operation_id}`, { exact: true })).toBeVisible();
  await commandView.close();
  expect((await (await page.request.get('/api/tags')).json()).values['CycleCommand.RequestSequence']).toBe(receipts[0].transaction.sequence);
  await page.unroute(dispatchEndpoint);
  await page.unroute(profilesEndpoint);
  await expect(panel.getByRole('alert')).toHaveCount(0);
  await expect(panel.locator('tbody tr').first()).toContainText('requested');
  expect((await (await page.request.get('/api/tags')).json()).values['CycleCommand.Running.RevisionId']).toBe(0);
  await page.goto('/runtime');
  await page.getByRole('button', { name: 'Simulate recipe PLC', exact: true }).click();
  await page.goto('/recipe-editor');
  const current = page.getByRole('region', { name: 'PLC recipe transfers', exact: true });
  await expect(current.locator('tbody tr').first()).toContainText('completed');
  await expect(current.getByRole('img', { name: 'Transfer fixture', exact: true })).toBeVisible();
  await page.getByLabel('Change / approval / load reason', { exact: true }).fill('Withdraw library approval; retain running copy');
  await page.getByRole('button', { name: 'Withdraw approval', exact: true }).click();
  await expect(page.locator('.recipe-review-state')).toContainText('withdrawn');
  await page.getByLabel('Change / approval / load reason', { exact: true }).fill('Transfer unapproved test copy');
  await page.getByRole('button', { name: 'Transfer revision to PLC', exact: true }).click();
  await expect(current.locator('tbody tr').first()).toContainText('Test / not production approved');
  const values = (await (await page.request.get('/api/tags')).json()).values;
  expect(values['CycleCommand.Running.RecipeProductionApproved']).toBe(true);
  expect(values['CycleCommand.Staging.RecipeProductionApproved']).toBe(false);
  await page.goto('/runtime');
  await page.getByRole('button', { name: 'Simulate recipe PLC', exact: true }).click();
  await page.goto('/recipes');
  const viewer = page.getByRole('region', { name: 'PLC recipe transfers', exact: true });
  await expect(viewer.locator('tbody tr').first()).toContainText('completed');
  await expect(viewer.locator('tbody tr')).toHaveCount(2);
  await viewer.getByRole('link', { name: `Transfer #${transaction.id}`, exact: true }).click();
  await expect(page.getByRole('heading', { name: `Transaction #${transaction.id}`, exact: true })).toBeVisible();
  await expect(page.locator('.activity-table tbody tr')).toHaveCount(1);
  await expect(page.locator('.activity-table tbody tr')).toContainText('completed');
  await page.getByRole('link', { name: 'All command transactions', exact: true }).click();
  await expect(page.locator('.activity-table tbody tr').filter({ hasText: 'recipe_cycle' })).toHaveCount(2);
  await page.goto('/recipes');
  expect((await (await page.request.get('/api/tags')).json()).values['CycleCommand.Running.RecipeProductionApproved']).toBe(false);
  await viewer.locator('tbody tr').first().getByText('Transfer details', { exact: true }).click();
  await expect(viewer.locator('tbody tr').first()).toContainText('production BOOL verified');
  const [download] = await Promise.all([page.waitForEvent('download'),
    viewer.getByRole('link', { name: 'Download recipe transfer JSON', exact: true }).click()]);
  const evidence = JSON.parse(await readFile(await download.path(), 'utf8'));
  expect(download.suggestedFilename()).toBe(`openhmi-recipe-transfer-${evidence.transfer.id}.json`);
  expect(evidence.transfer.snapshot).toMatchObject({ code: 'TRANSFER-DEMO', production_approved: false });
  expect(evidence.transfer.envelope.values.RecipeProductionApproved).toBe(false);
  expect(evidence.transfer.transaction).toMatchObject({ command_id: 'recipe_cycle', state: 'completed' });
  if (process.env.OPENHMI_RECIPE_TRANSFER_SCREENSHOT) await page.screenshot({ path: process.env.OPENHMI_RECIPE_TRANSFER_SCREENSHOT, fullPage: true });
  expect(errors).toEqual([]);
  await apply(original);
});
