import { test, expect } from '@playwright/test';

test('add project languages, translate controls and show only configured flags', async ({ page, context }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Languages', exact: true }).click();
  await page.getByLabel('New language code').fill('zh-CN');
  await page.getByLabel('New language name').fill('简体中文');
  await page.getByLabel('New language flag').selectOption('cn');
  await page.getByRole('button', { name: 'Add language', exact: true }).click();
  await page.getByLabel('screen.title translation', { exact: true }).fill('站点总览');
  await page.getByLabel('control.level.label translation', { exact: true }).fill('液位');
  await page.getByLabel('alarm.process_alarm.message translation', { exact: true }).fill('工艺报警');
  await page.getByLabel('New language code').fill('es');
  await page.getByLabel('New language name').fill('Español');
  await page.getByLabel('New language flag').selectOption('mx');
  await page.getByRole('button', { name: 'Add language', exact: true }).click();
  await page.getByLabel('screen.title translation', { exact: true }).fill('Vista general');
  await page.getByRole('button', { name: 'Apply live', exact: true }).click();
  await expect(page.getByRole('status', { name: 'Draft status' })).toContainText('Applied live');
  const viewer = await context.newPage();
  await viewer.goto('/runtime');
  const trigger = viewer.getByRole('button', { name: 'Language: English', exact: true });
  await trigger.press('ArrowUp');
  const menu = viewer.getByRole('menu', { name: 'Configured languages' });
  const spanish = menu.getByRole('menuitem', { name: 'Español' });
  const chinese = menu.getByRole('menuitem', { name: '简体中文' });
  await expect(menu.getByRole('menuitem')).toHaveCount(2);
  await expect(menu.locator('img')).toHaveCount(2);
  await expect(menu.locator('img[src$="/cn.svg"]')).toHaveCount(1);
  await expect(menu.locator('img[src$="/mx.svg"]')).toHaveCount(1);
  await expect(menu.locator('img[src$="/fr.svg"]')).toHaveCount(0);
  if (process.env.OPENHMI_LANGUAGE_MENU) await viewer.screenshot({ path: process.env.OPENHMI_LANGUAGE_MENU, fullPage: true });
  await expect(spanish).toBeFocused();
  await viewer.keyboard.press('ArrowDown');
  await expect(chinese).toBeFocused();
  await viewer.keyboard.press('End');
  await expect(spanish).toBeFocused();
  await viewer.keyboard.press('Home');
  await expect(chinese).toBeFocused();
  await viewer.keyboard.press('Escape');
  await expect(trigger).toBeFocused();
  await expect(menu).toHaveCount(0);
  await trigger.click();
  await expect(chinese).toBeFocused();
  await trigger.click();
  await expect(menu).toHaveCount(0);
  await trigger.press('Enter');
  await viewer.keyboard.press('Tab');
  await expect(menu).toHaveCount(0);
  await expect(trigger).not.toBeFocused();
  await trigger.press('ArrowDown');
  await viewer.locator('.station-title h1').click();
  await expect(menu).toHaveCount(0);
  await trigger.press('ArrowDown');
  await viewer.keyboard.press('Enter');
  await expect(viewer.getByRole('button', { name: 'Language: 简体中文', exact: true })).toBeFocused();
  await expect(viewer.locator('.station-title h1')).toHaveText('站点总览');
  await expect(viewer.locator('[data-control="numeric"]').filter({ hasText: '液位' })).toHaveCount(1);
  await viewer.evaluate(() => document.fonts.load('12.42px "OpenHMI Noto"'));
  expect(await viewer.evaluate(() => document.fonts.check('12.42px "OpenHMI Noto"'))).toBe(true);
  if (process.env.OPENHMI_LANGUAGE_SCREENSHOT) await viewer.screenshot({ path: process.env.OPENHMI_LANGUAGE_SCREENSHOT, fullPage: true });
  await viewer.reload();
  await expect(viewer.locator('.station-title h1')).toHaveText('站点总览');
  await viewer.getByRole('button', { name: 'Language: 简体中文', exact: true }).click();
  await viewer.getByRole('menuitem', { name: 'English', exact: true }).click();
  await expect(viewer.locator('.station-title h1')).toHaveText('Station overview');
  const state = await (await page.request.get('/api/project')).json();
  expect(state.active.languages.map(language => language.code)).toEqual(['en', 'zh-CN', 'es']);
  expect(state.active.alarms[0].tag).toBe('ProcessAlarm');
});

test('project-wide alarms work without an alarm graphic and acknowledge independently of return', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Alarm setup', exact: true }).click();
  const definition = page.getByRole('group', { name: 'process_alarm', exact: true });
  await definition.getByLabel('Alarm message', { exact: true }).fill('Drive fault');
  const steps = '1. Review the drive fault code.\n2. Follow the drive recovery procedure.';
  await definition.getByLabel('process_alarm recovery steps', { exact: true }).fill(steps);
  await definition.getByRole('combobox', { name: 'Priority', exact: true }).selectOption('1');
  await page.getByRole('button', { name: 'Apply live', exact: true }).click();
  await expect(page.getByRole('status', { name: 'Draft status' })).toContainText('Applied live');
  const state = await (await page.request.get('/api/project')).json();
  const project = state.draft;
  project.controls.find(control => control.kind === 'numeric').unit = '';
  project.controls = project.controls.filter(control => control.kind !== 'alarm');
  const command = project.controls.find(control => control.kind === 'button');
  command.action = 'toggle_alarm';
  command.label = 'Toggle process alarm';
  const saved = await page.request.put('/api/project/draft', { data: { expected_revision: state.draft_revision, project } });
  expect(saved.ok()).toBe(true);
  const applied = await page.request.post('/api/project/apply', { data: { expected_revision: (await saved.json()).draft_revision } });
  expect(applied.ok()).toBe(true);
  await page.goto('/runtime');
  await expect(page.locator('[data-control="alarm"]')).toHaveCount(0);
  await expect(page.locator('[data-control="numeric"]').first().locator('small')).toHaveText('');
  await page.getByRole('button', { name: 'Toggle process alarm', exact: true }).click();
  await expect(page.getByLabel('Screen alarm status')).toContainText('P1 Drive fault');
  await page.goto('/alarms');
  await expect(page.getByRole('cell', { name: 'Drive fault', exact: true })).not.toHaveCount(0);
  const alarm = page.getByRole('row').filter({ has: page.getByRole('button', { name: 'Acknowledge Drive fault', exact: true }) });
  await alarm.getByRole('button', { name: /^Details / }).click();
  const detail = page.getByRole('region', { name: 'Alarm details', exact: true });
  await expect(detail.getByRole('heading', { name: 'Recovery steps', exact: true })).toBeVisible();
  const guidance = detail.locator('.alarm-guidance').nth(1);
  await expect.poll(() => guidance.textContent()).toBe(steps);
  await expect(guidance).toHaveCSS('white-space', 'pre-wrap');
  await page.getByRole('button', { name: 'Acknowledge Drive fault', exact: true }).click();
  await expect(page.getByText('1 active / 0 unacknowledged', { exact: true })).toBeVisible();
  if (process.env.OPENHMI_ALARM_CONSOLE) await page.screenshot({ path: process.env.OPENHMI_ALARM_CONSOLE, fullPage: true });
  await page.goto('/runtime');
  await page.getByRole('button', { name: 'Toggle process alarm', exact: true }).click();
  await expect(page.getByLabel('Screen alarm status')).toContainText('No active or unacknowledged alarms');
  await page.goto('/alarms');
  await expect(page.getByText('No outstanding alarms', { exact: true })).toBeVisible();
  await expect(page.getByRole('cell', { name: 'Returned', exact: true })).toBeVisible();
  await expect(page.getByRole('cell', { name: 'Acknowledged', exact: true })).toBeVisible();
});
